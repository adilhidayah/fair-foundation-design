// Export of the Summary report as ONE standalone HTML file (same document format as the CLI reports: css/report.css +
// lib/foundation/report/reportDocument.js), with a Print / Save as PDF button on top. Declarations only — wiring is in app.js.
// The Summary panel (#calc-summary) is the report the user sees in Report Preview: its HTML is taken as is (full tables), and the SVG diagrams,
// which are styled by the app's stylesheet, get their computed style written into the elements so they look the same outside the app.
import { buildReportDocument } from '../../lib/foundation/index.js?v=20261015k';
import { state } from '../core/state.js?v=20261015k';
import { generateReport } from '../report/builder.js?v=20261015k';

const SVG_PROPS = ['fill', 'stroke', 'stroke-width', 'stroke-dasharray', 'stroke-linecap', 'stroke-linejoin', 'fill-opacity', 'stroke-opacity', 'opacity',
  'font-family', 'font-size', 'font-weight', 'text-anchor', 'dominant-baseline', 'paint-order', 'letter-spacing'];

// Clone of the Summary panel with the computed SVG styles written as style attributes, always in the light palette (print look).
export function summaryBodyHtml() {
  const panel = document.getElementById('calc-summary');
  const root = document.documentElement, prevTheme = root.getAttribute('data-theme');
  root.setAttribute('data-theme', 'light');
  try {
    const clone = panel.cloneNode(true);
    const live = [...panel.querySelectorAll('svg, svg *')], cl = [...clone.querySelectorAll('svg, svg *')];
    live.forEach((el, i) => {
      if (!cl[i]) return;
      const cs = getComputedStyle(el);
      const st = SVG_PROPS.map((p) => { const v = cs.getPropertyValue(p); return v ? `${p}:${v}` : ''; }).filter(Boolean).join(';');
      if (st) cl[i].setAttribute('style', (cl[i].getAttribute('style') || '') + ';' + st);
    });
    clone.querySelectorAll('.lt-bar').forEach((e) => e.remove());   // "Show all N rows" buttons: the export holds every row
    clone.querySelectorAll('[data-lt]').forEach((e) => { e.removeAttribute('data-lt'); e.removeAttribute('data-lt-open'); });
    return clone.innerHTML;
  } finally {
    if (prevTheme === null) root.removeAttribute('data-theme'); else root.setAttribute('data-theme', prevTheme);
  }
}
export async function buildAppReportDocument() {
  generateReport();   // refresh the Summary from the panels' latest results
  const css = await (await fetch('css/report.css')).text();
  const val = (id) => (document.getElementById(id) || {}).value || '';
  const useDoc = !!(document.getElementById('rpt-use-docheader') || {}).checked;
  const meta = { project: val('rpt-project') || 'Untitled Project', location: val('rpt-location'), by: val('rpt-by'), date: val('rpt-date'), rev: val('rpt-rev') || '0',
    ...(useDoc ? { companyDocId: val('rpt-companyDocId'), contractorDocId: val('rpt-contractorDocId'), pages: val('rpt-pages'), logo1: state.rptLogo1 || '', logo2: state.rptLogo2 || '' } : {}) };
  return { html: buildReportDocument({ title: 'Foundation calculation report', meta, bodyHtml: summaryBodyHtml(), css, header: false,
    footer: 'Generated by FAIR Foundation Design. Results are for checking by a qualified engineer; verify against the project design basis.' }), meta };
}
export async function exportReportHtml() {
  const { html, meta } = await buildAppReportDocument();
  const name = (meta.project || 'report').replace(/[\\/:*?"<>|]+/g, '-').trim() || 'report';
  const url = URL.createObjectURL(new Blob([html], { type: 'text/html;charset=utf-8' }));
  const a = document.createElement('a');
  a.href = url; a.download = `${name} - Calculation Report.html`;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
